/**
 * Пакетная ЗАГРУЗКА графа: paper не перерисовывает view, пока в модель валятся сотни
 * ячеек (`graph.fromJSON`).
 *
 * ВНУТРЬ НЕЛЬЗЯ заворачивать инъекцию разметки (всё, что ходит через
 * `paper.findViewByModel`): у замороженного paper'а представлений новых ячеек ещё
 * нет, инъекция молча ничего не делает, а после разморозки JointJS рисует ячейки
 * пустым `body` — на схеме остаются только провода. Порядок: заморозка на
 * `fromJSON`, инъекция после.
 *
 * `unfreeze` в finally: залипший freeze выглядит как зависший редактор (правки идут
 * в модель, на экране ничего). Методы опциональны — в тестах paper это мок.
 */
export function withPaperFrozen(paper, fn) {
  paper?.freeze?.()
  try {
    return fn()
  } finally {
    paper?.unfreeze?.()
  }
}
